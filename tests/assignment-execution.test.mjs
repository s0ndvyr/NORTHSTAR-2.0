import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
const E=createRequire(import.meta.url)('../scripts/assignment-execution.js');
const c=E.classify;
assert.equal(c({submission_types:['online_upload']}).kind,'file_upload');
assert.equal(c({submission_types:['online_text_entry','online_url']}).kind,'text_entry');
assert.equal(c({submission_types:['online_url']}).launchMethod,'canvas_submission_api');
assert.equal(c({submission_types:['online_quiz']}).kind,'quiz');
assert.equal(c({submission_types:['discussion_topic']}).kind,'discussion');
assert.equal(c({submission_types:['student_annotation'],annotatable_attachment_id:442}).annotatableAttachmentId,442);
assert.equal(c({submission_types:['student_annotation']}).kind,'student_annotation');
assert.equal(c({submission_types:['external_tool'],external_tool:{name:'Google Assignments'}}).kind,'google_assignments');
assert.equal(c({submission_types:['external_tool'],external_tool:{name:'Google Drive LTI'}}).kind,'google_drive_lti');
assert.equal(c({submission_types:['external_tool'],external_tool:{name:'School Publisher'}}).kind,'external_tool');
assert.equal(c({name:'Google Docs Essay',submission_types:['online_upload']}).kind,'file_upload');
assert.equal(c({submission_types:['online_upload'],external_tool_tag_attributes:{url:'https://assignments.google.com'}}).kind,'file_upload');
assert.equal(c({submission_types:['on_paper']}).kind,'offline_paper');
assert.equal(c({submission_types:['none']}).kind,'offline');
assert.equal(c({submission_types:['future_type']}).kind,'unknown');
assert.equal(c({submission_types:['external_tool']}).launchMethod,'sessionless_launch');
assert.equal(c({submission_types:['online_upload'],published:false}).available,false);
assert.equal(c({submission_types:['online_upload'],locked_for_user:true}).available,false);
assert.equal(c({submission_types:['online_upload'],can_submit:false}).resubmissionAllowed,false);
assert.equal(c({submission_types:['online_upload'],can_submit:true}).resubmissionAllowed,true);
assert.equal(c({submission_types:['external_tool','online_upload']}).kind,'external_tool');
assert.deepEqual(c({submission_types:['online_upload','future_type']}).unknownSubmissionTypes,['future_type']);
console.log('assignment-execution: all assertions passed');
